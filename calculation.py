class Calculator:
    def __init__(self):
        pass

    def addition(self, x, y):
        return x + y

    def subtraction(self, x, y):
        return x - y

    def multiplication(self, x, y):
        return x * y

    def division(self, x, y):
        return x / y

    # division with rounded (floor) result
    def division_floor(self, x, y):
        return x // y